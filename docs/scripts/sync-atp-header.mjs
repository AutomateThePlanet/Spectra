// Regenerates the automatetheplanet.com MENU of the SPECTRA docs header from the ATP website, so the menu items
// always match automatetheplanet.com. Only the menu: the header itself (SPECTRA logo, search, "Get SPECTRA" button,
// white bar) is SPECTRA's own (_includes/atp_header.html, header_custom.html, custom.scss).
//   node docs/scripts/sync-atp-header.mjs [path-to-Automate-The-Planet-Website-v2]
// Writes docs/_includes/atp_nav.html (never edit it by hand):
//   - the top-level items of src/components/layout/Header.astro (#menu-main) and their sub-menus, in the markup
//     custom.scss styles (.atp-nav-list / .atp-nav-item / .atp-nav-link / .atp-sub)
//   - links absolute to https://www.automatetheplanet.com, internal paths with their final trailing slash
//   - Tools = the current section (is-current), SPECTRA = the current item (aria-current="page")
//   - items without a page of their own ("#": Tools, Company) are buttons that open their sub-menu
//   - the site's dark/light theme toggle is left out; "Contact Us" (a button on the site) is a plain menu link
import fs from 'node:fs';
import path from 'node:path';

const ATP = path.resolve(process.argv[2] || 'C:/Users/angel/OneDrive/WORKING_COWORK/Automate-The-Planet-Website-v2');
const DOCS = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..');
const SITE = 'https://www.automatetheplanet.com';

const src = fs.readFileSync(path.join(ATP, 'src/components/layout/Header.astro'), 'utf8');
const menuStart = src.indexOf('<ul id="menu-main"');
if (menuStart < 0) throw new Error('#menu-main not found in Header.astro');

// minimal parser for the nested <ul>/<li>/<a> list of #menu-main
const tokens = [...src.slice(menuStart).matchAll(/<(\/?)(ul|li|a)\b([^>]*)>|([^<]+)/g)];
let depth = 0;
const root = { children: [] };
const stack = [root];
let currentA = null;
for (const t of tokens) {
  const [, close, tag, attrs, text] = t;
  if (text !== undefined) { if (currentA) currentA.label += text; continue; }
  if (tag === 'ul') {
    if (close) { depth--; stack.pop(); if (depth === 0) break; }
    else { depth++; const top = stack[stack.length - 1]; const list = top === root ? root : (top.sub = { children: [] }); stack.push(list); }
  } else if (tag === 'li') {
    if (close) stack.pop();
    else { const item = { attrs, sub: null, label: '', href: null }; stack[stack.length - 1].children.push(item); stack.push(item); }
  } else if (tag === 'a') {
    if (close) currentA = null;
    else { const item = stack[stack.length - 1]; const href = (attrs.match(/href="([^"]*)"/) || [])[1]; if (item.href === null && href !== undefined) { item.href = href; currentA = item; } }
  }
}
const items = root.children.filter((i) => i.href !== null); // drops the theme-toggle <li>
const clean = (s) => s.replace(/\s+/g, ' ').trim();
const url = (href) => {
  if (!href || href === '#') return null;
  let [p, hash] = href.split('#');
  if (p.startsWith('/') && !/\.[a-z0-9]+$/i.test(p) && !p.endsWith('/')) p += '/';
  return (p.startsWith('/') ? SITE + p : p) + (hash !== undefined ? '#' + hash : '');
};
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;');

const out = [];
out.push('{%- comment -%}GENERATED by docs/scripts/sync-atp-header.mjs from the automatetheplanet.com menu');
out.push('(Automate-The-Planet-Website-v2/src/components/layout/Header.astro). Never edit by hand.{%- endcomment -%}');
out.push('<nav class="atp-nav" aria-label="Automate The Planet">');
out.push('  <ul class="atp-nav-list">');
let tools = false, spectra = false;
for (const it of items) {
  const label = clean(it.label);
  const sub = it.sub ? it.sub.children.filter((c) => c.href !== null) : [];
  const isTools = label === 'Tools';
  tools = tools || isTools;
  const cls = ['atp-nav-item', sub.length ? 'has-sub' : '', isTools ? 'is-current' : ''].filter(Boolean).join(' ');
  const href = url(it.href);
  out.push(`    <li class="${cls}">`);
  out.push(href
    ? `      <a class="atp-nav-link" href="${href}">${esc(label)}</a>`
    : `      <button type="button" class="atp-nav-link btn-reset" aria-haspopup="true">${esc(label)}</button>`);
  if (sub.length) {
    const wide = sub.some((c) => clean(c.label).length > 40);
    out.push(`      <ul class="atp-sub${wide ? ' atp-sub-wide' : ''}">`);
    for (const c of sub) {
      const cl = clean(c.label), ch = url(c.href);
      const current = isTools && cl === 'SPECTRA';
      spectra = spectra || current;
      out.push(`        <li><a href="${ch}"${current ? ' aria-current="page"' : ''}>${esc(cl)}</a></li>`);
    }
    out.push('      </ul>');
  }
  out.push('    </li>');
}
out.push('  </ul>');
out.push('</nav>');
if (!tools || !spectra) throw new Error('Tools / SPECTRA not found in the ATP menu');
fs.writeFileSync(path.join(DOCS, '_includes/atp_nav.html'), out.join('\n') + '\n');
console.log(`atp_nav.html: ${items.length} menu items (${items.map((i) => clean(i.label)).join(', ')})`);
