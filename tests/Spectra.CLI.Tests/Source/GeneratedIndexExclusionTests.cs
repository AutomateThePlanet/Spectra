using System.Text.Json;
using Spectra.CLI.Dashboard;
using Spectra.CLI.Source;
using Spectra.Core.Coverage;
using Spectra.Core.Models;
using Spectra.Core.Models.Config;

namespace Spectra.CLI.Tests.Source;

/// <summary>
/// SPECTRA's own docs index (<c>docs/_index.md</c>, <c>docs/_index/**</c>) is not documentation. Up to 2.7.0 the
/// document map used by coverage and <c>docs changed</c> included <c>docs/_index/groups/*.index.md</c>, so a fully
/// covered repository reported 7/8 documents (87.5%) and the index file showed up as an uncovered document.
/// </summary>
public sealed class GeneratedIndexExclusionTests : IDisposable
{
    private readonly string _root = Path.Combine(Path.GetTempPath(), $"spectra-genindex-{Guid.NewGuid():N}");

    public GeneratedIndexExclusionTests()
    {
        Write("docs/checkout.md", "# Checkout\n\n## Payment\n\nThe user pays by card.\n");
        Write("docs/_index.md", "# Legacy index\n\nGenerated by an older SPECTRA.\n");
        Write("docs/_index/_manifest.yaml", "version: 2\n");
        Write("docs/_index/groups/_root.index.md", "# _root\n\n> Group: _root | 1 documents\n");
    }

    public void Dispose()
    {
        if (Directory.Exists(_root))
        {
            Directory.Delete(_root, recursive: true);
        }
    }

    private void Write(string relative, string content)
    {
        var path = Path.Combine(_root, relative.Replace('/', Path.DirectorySeparatorChar));
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, content);
    }

    [Fact]
    public async Task DocumentMap_AndDocumentationCoverage_CountOnlyRealDocuments()
    {
        var map = await new DocumentMapBuilder(new SourceConfig()).BuildAsync(_root);

        Assert.Equal(["docs/checkout.md"], map.Documents.Select(d => d.Path).ToArray());

        var coverage = new DocumentationCoverageAnalyzer().Analyze(map, Array.Empty<TestCase>());
        Assert.Equal(1, coverage.TotalDocs);
    }

    [Fact]
    public async Task DashboardDocumentationCoverage_CountsOnlyRealDocuments()
    {
        var suiteDir = Path.Combine(_root, "test-cases", "checkout");
        Directory.CreateDirectory(suiteDir);
        var index = new MetadataIndex
        {
            Suite = "checkout",
            GeneratedAt = DateTime.UtcNow,
            Tests =
            [
                new TestIndexEntry
                {
                    Id = "TC-001", Title = "Pay by card", File = "TC-001.md", Priority = "high", Tags = [],
                    SourceRefs = ["docs/checkout.md#Payment"],
                },
            ],
        };
        await File.WriteAllTextAsync(Path.Combine(suiteDir, "_index.json"), JsonSerializer.Serialize(index,
            new JsonSerializerOptions { PropertyNamingPolicy = JsonNamingPolicy.SnakeCaseLower }));

        var data = await new DataCollector(_root).CollectAsync();

        var docs = data.CoverageSummary!.Documentation;
        Assert.Equal(1, docs.Total);
        Assert.Equal(1, docs.Covered);
        Assert.DoesNotContain(docs.Details!, d => d.Doc.Contains("_index", StringComparison.Ordinal));
    }

    [Theory]
    [InlineData("docs/_index.md", true)]
    [InlineData("docs/_index/groups/_root.index.md", true)]
    [InlineData("docs\\_index\\_manifest.yaml", true)]
    [InlineData("docs/checkout.md", false)]
    [InlineData("docs/_indexing-guide.md", false)]
    public void GeneratedIndexMatcher_MatchesOnlyTheIndexFiles(string relativePath, bool expected)
    {
        var isGenerated = DocumentIndexService.GeneratedIndexMatcher(_root, new SourceConfig());

        Assert.Equal(expected, isGenerated(relativePath));
    }
}
